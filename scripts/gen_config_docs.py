"""
Generate `.env.example` and the README configuration table from app/config.py.

    python scripts/gen_config_docs.py           # rewrite both
    python scripts/gen_config_docs.py --check   # exit 1 if either is out of date (CI)

`Settings` is the single source of truth: a variable's name, default and
description are written there once. Hand-editing the generated files is
pointless — the next run overwrites them and CI rejects the drift.
"""
from __future__ import annotations

import argparse
import sys
import textwrap
import typing
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from pydantic import SecretStr  # noqa: E402

from app.config import GROUPS, Settings  # noqa: E402
from app.utils.logging import get_logger  # noqa: E402

logger = get_logger('gen_config_docs')

ENV_EXAMPLE = ROOT / '.env.example'
README = ROOT / 'README.md'
README_START = '<!-- config:start (generated by scripts/gen_config_docs.py; do not edit) -->'
README_END = '<!-- config:end -->'


def _fields_by_group():
    grouped: dict[str, list] = {key: [] for key in GROUPS}
    for name, field in Settings.model_fields.items():
        grouped[field.json_schema_extra['group']].append((name, field))
    return grouped


def _value(value) -> str:
    """A default as it would be written in an env file."""
    if isinstance(value, SecretStr):
        value = value.get_secret_value()
    if value is None:
        return ''
    if isinstance(value, bool):
        return 'true' if value else 'false'
    return str(value)


def _choices(field) -> list[str]:
    annotation = field.annotation
    if typing.get_origin(annotation) is typing.Literal:
        return [str(a) for a in typing.get_args(annotation)]
    return []


def _description(field) -> str:
    text = field.description or ''
    choices = _choices(field)
    if choices:
        text += f" One of: {', '.join(choices)}."
    return text


def render_env_example() -> str:
    lines = [
        '# Generated from app/config.py by scripts/gen_config_docs.py — do not edit.',
        '# Copy to .env and fill in. Commented lines show the default (or an example);',
        '# uncomment one only to change it. An empty value also means "use the default".',
        '#',
        '# IITA Internal Use',
    ]
    for group, fields in _fields_by_group().items():
        if not fields:
            continue
        lines += ['', f'# ── {GROUPS[group]} ' + '─' * max(3, 70 - len(GROUPS[group]))]
        for name, field in fields:
            extra = field.json_schema_extra
            for chunk in textwrap.wrap(_description(field), width=86):
                lines.append(f'# {chunk}')
            shown = extra.get('example', _value(field.default))
            if extra.get('active'):
                lines.append(f'{name}={shown}')
            else:
                lines.append(f'# {name}={shown}')
    return '\n'.join(lines) + '\n'


def _cell(text: str) -> str:
    return text.replace('|', '\\|')


def render_readme_table() -> str:
    out = [README_START, '']
    for group, fields in _fields_by_group().items():
        if not fields:
            continue
        out += [f'**{GROUPS[group]}**', '', '| Variable | Default | Description |', '|---|---|---|']
        for name, field in fields:
            default = _value(field.default)
            shown = '—' if default == '' else f'`{_cell(default)}`'
            out.append(f'| `{name}` | {shown} | {_cell(_description(field))} |')
        out.append('')
    out.append(README_END)
    return '\n'.join(out)


def _replace_readme_block(readme: str, block: str) -> str:
    start = readme.find(README_START)
    end = readme.find(README_END)
    if start < 0 or end < start:
        raise SystemExit(f'README.md has no {README_START!r} … {README_END!r} block')
    return readme[:start] + block + readme[end + len(README_END):]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    parser.add_argument('--check', action='store_true', help='Fail if a generated file is out of date')
    args = parser.parse_args()

    readme_now = README.read_text(encoding='utf-8')
    targets = {
        ENV_EXAMPLE: render_env_example(),
        README: _replace_readme_block(readme_now, render_readme_table()),
    }

    stale = []
    for path, wanted in targets.items():
        current = path.read_text(encoding='utf-8') if path.exists() else ''
        if current.replace('\r\n', '\n') == wanted.replace('\r\n', '\n'):
            continue
        stale.append(path.name)
        if not args.check:
            path.write_text(wanted, encoding='utf-8', newline='\n')
            logger.info('updated', file=path.name)

    if args.check and stale:
        logger.error('configuration docs are out of date; run `make config-docs`', files=stale)
        return 1
    if not stale:
        logger.info('configuration docs are up to date')
    return 0


if __name__ == '__main__':
    sys.exit(main())
